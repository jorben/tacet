package coverage

import "sort"

// Fate is what a plugin's write reported for an input part (MD-14).
type Fate string

const (
	FateKept      Fate = "kept"
	FateRedacted  Fate = "redacted"
	FateRemoved   Fate = "removed"
	FateConverted Fate = "converted"
)

type InputPart struct {
	ID          string
	ContentType string
}

// Destination is the plugin's claim for one input part.
type Destination struct {
	PartID string
	Fate   Fate
	// ExpectedType is required for converted parts; kept and redacted parts must
	// keep the input content type.
	ExpectedType string
}

// OutputPart is a part found by re-enumerating the candidate.
type OutputPart struct {
	ID          string
	ContentType string
	// SourceID links the output to the input part it came from; empty for
	// parts the plugin declared as newly generated.
	SourceID string
	// References are the ids of other output parts this one points to.
	References []string
}

type MismatchKind string

const (
	MissingDestination   MismatchKind = "input_part_without_destination"
	UnknownSource        MismatchKind = "destination_for_unknown_input"
	DuplicateDestination MismatchKind = "duplicate_destination"
	UnregisteredOutput   MismatchKind = "output_without_source_or_declaration"
	RemovedStillPresent  MismatchKind = "removed_part_present"
	DanglingReference    MismatchKind = "reference_to_removed_part"
	KeptMissing          MismatchKind = "kept_part_missing"
	ContentTypeMismatch  MismatchKind = "content_type_mismatch"
	DuplicateOutput      MismatchKind = "duplicate_output_id"
	InvalidFate          MismatchKind = "invalid_fate"
)

// Mismatch carries only ids, never part content.
type Mismatch struct {
	Kind   MismatchKind
	PartID string
}

// Reconcile compares write's claims with the re-enumerated output. Any entry
// in the result fails the file (8.2); the plugin's own verdict is advisory.
// inputComplete=false is an error, since a partial inventory cannot be reconciled.
func Reconcile(input []InputPart, dest []Destination, output []OutputPart, inputComplete, outputComplete bool) ([]Mismatch, error) {
	if !inputComplete || !outputComplete {
		return nil, ErrInventoryIncomplete
	}
	var out []Mismatch
	in := map[string]InputPart{}
	for _, p := range input {
		in[p.ID] = p
	}
	claims := map[string]Destination{}
	for _, d := range dest {
		if _, ok := in[d.PartID]; !ok {
			out = append(out, Mismatch{UnknownSource, d.PartID})
			continue
		}
		if _, dup := claims[d.PartID]; dup {
			out = append(out, Mismatch{DuplicateDestination, d.PartID})
			continue
		}
		switch d.Fate {
		case FateKept, FateRedacted, FateRemoved:
		case FateConverted:
			if d.ExpectedType == "" {
				out = append(out, Mismatch{InvalidFate, d.PartID})
				continue
			}
		default:
			out = append(out, Mismatch{InvalidFate, d.PartID})
			continue
		}
		claims[d.PartID] = d
	}
	for _, p := range input {
		if _, ok := claims[p.ID]; !ok {
			out = append(out, Mismatch{MissingDestination, p.ID})
		}
	}
	present := map[string]OutputPart{}
	bySource := map[string][]OutputPart{}
	for _, o := range output {
		if _, dup := present[o.ID]; dup {
			out = append(out, Mismatch{DuplicateOutput, o.ID})
			continue
		}
		present[o.ID] = o
		if o.SourceID == "" {
			continue // declared as newly generated by the plugin
		}
		d, ok := claims[o.SourceID]
		if !ok {
			out = append(out, Mismatch{UnregisteredOutput, o.ID})
			continue
		}
		bySource[o.SourceID] = append(bySource[o.SourceID], o)
		if d.Fate == FateRemoved {
			out = append(out, Mismatch{RemovedStillPresent, o.SourceID})
			continue
		}
		want := in[o.SourceID].ContentType
		if d.Fate == FateConverted {
			want = d.ExpectedType
		}
		if o.ContentType != want {
			out = append(out, Mismatch{ContentTypeMismatch, o.ID})
		}
	}
	removedOutputs := map[string]bool{}
	for id, d := range claims {
		if d.Fate == FateRemoved {
			removedOutputs[id] = true
		}
	}
	for _, o := range present {
		for _, ref := range o.References {
			// A reference may name an input id that was removed, or an output
			// id whose source was removed.
			if removedOutputs[ref] {
				out = append(out, Mismatch{DanglingReference, o.ID})
			} else if t, ok := present[ref]; ok && t.SourceID != "" && claims[t.SourceID].Fate == FateRemoved {
				out = append(out, Mismatch{DanglingReference, o.ID})
			}
		}
	}
	for id, d := range claims {
		if d.Fate != FateRemoved && len(bySource[id]) == 0 {
			out = append(out, Mismatch{KeptMissing, id})
		}
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Kind != out[j].Kind {
			return out[i].Kind < out[j].Kind
		}
		return out[i].PartID < out[j].PartID
	})
	return out, nil
}
